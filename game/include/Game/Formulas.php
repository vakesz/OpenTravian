    /**
     * Celebration culture-point caps at the published speed points (x1, x2,
     * x3, x5, x10). Unpublished speeds are interpolated linearly between the
     * neighbouring points and speeds above x10 keep the x10 value, matching
     * the README world-speed profile.
     *
     * @param mixed $big
     * @param mixed $speed
     * @return (float|int)|int
     */
    public static function celebrationCpAtSpeed($big, $speed)
    {
        $points = $big
            ? [1 => 2000, 2 => 2000, 3 => 1000, 5 => 1000, 10 => 500]
            : [1 => 500, 2 => 500, 3 => 250, 5 => 250, 10 => 125];
        $speed = max(1, min(10, $speed));
        if (floor($speed) == $speed && isset($points[(int)$speed])) {
            return $points[(int)$speed];
        }
        $lower = max(array_filter(array_keys($points), fn($p) => $p < $speed));
        $upper = min(array_filter(array_keys($points), fn($p) => $p > $speed));
        $ratio = ($speed - $lower) / ($upper - $lower);

        return $points[$lower] + ($points[$upper] - $points[$lower]) * $ratio;
    }

