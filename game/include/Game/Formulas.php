    public static function getMapMinDistanceFromCenter($elapsed = null, $rate = 1)
    {
        if (is_null($elapsed)) {
            $elapsed = getGameElapsedMiliSeconds();
            $rate = 1000;
        }
        $elapsed = max(0, $elapsed);
        $round_length = getGame('round_length_real');
        if (getGameSpeed() <= 10) {
