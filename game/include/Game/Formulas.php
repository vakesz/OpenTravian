    /**
     * @param mixed $type
     * @return mixed
     */
    public static function getOasisEffect($type)
    {
        if (!isset(self::$data['oases'][$type])) {
            return [];
        }
        return self::$data['oases'][$type];
    }

    /**
     * @param int $type
     * @return array<int, (float|int)>
     */
    public static function getOasisProduction($type)
    {
        $production = array_fill(0, 4, getGameSpeed() * 10);
        foreach (self::getOasisEffect($type) as $k => $v) {
            if (!$v) {
                continue;
            }
            $production[$k - 1] *= 4 * $v;
        }
        return $production;
    }

    /**
     * @return float|int
     */
    public static function minVacationDays()
    {
        return max(round(3 / getGameSpeed()), 1);
    }

    public static function maxVacationDays(): int
    {
        $baseDays = (int)Config::getProperty("game", "vacationDays");
        if ($baseDays <= 0) {
            return 0;
        }
        $speed = getGameSpeed();
        $minimum = WorldSpeedProfile::isOfficialLegendsSpeed($speed) ? 1 : 3;
        return max((int)round($baseDays / $speed), $minimum);
    }

    public static function remainingVacationDays(int $usedDays): int
    {
        return max(0, self::maxVacationDays() - $usedDays);
    }

    /**
     * @param mixed $x
     * @param mixed $y
     */
    public static function getAngleByXY($x, $y): float
    {
        $angle = rad2deg(atan2($y, $x));
        if ($angle < 0) {
            $angle += 360;
        }
        return $angle;
    }

    public static function getTrapRepairTime(): float
    {
        $ub = getGameSpeed();
        if ($ub <= 10) {
            $ub = 1;
        }
        $time = 60;
        $time /= $ub;
        $time *= Config::getProperty("game", "useNanoseconds") ? 1e9 : (Config::getProperty("game",
            "useMilSeconds") ? 1e3 : 1);
        if (getGameSpeed() <= 10) {
            return round($time);
        }
        return floor($time);
    }

    /**
     * @param mixed $u
     * @param mixed $blevel
     * @param mixed $hdp
     * @param array<mixed> $h
     * @param mixed $art_eff
     * @param mixed $decrease_percent
     * @param mixed $alliance_effect
     * @return float|int
     */
    public static function uTrainingTime($u, $blevel, $hdp = 0, array $h = [
        0,
        0
    ], $art_eff = 1, $decrease_percent = 0, $alliance_effect = 1)
    {
        $ub = getGameSpeed();
        $ub *= getGame('extra_training_time_multiplier');
        if ($u == 99) {
            $time = 600;
            $race = 2;
        } else {
            $race = unitIdToTribe($u) - 1;
            $u = unitIdToNr($u) - 1;
            $time = self::$data['units'][$race][$u]['time'];
        }
        if ($u < 6) {
            $ci = \Game\Tribes::CAVALRY_START[$race + 1];
            $time /= $ub;
            if ($u < $ci) { // trained in barracks
                $time *= (1 - $h[0] / 100);//hero
            } else { // trained in stables
                $time *= (1 - $h[1] / 100);
            }
        } else {
            $time /= $ub;
        }
        if ($race == 0 && 3 <= $u && $u <= 5) {
            $time *= 1 - 0.01 * $hdp;
        }
        $rate = Config::getProperty("game", "useNanoseconds") ? 1e9 : (Config::getProperty("game", "useMilSeconds") ? 1e3 : 1);
        $time = ($time * pow(0.9, $blevel - 1) * $rate);
        $time *= $art_eff;
        if ($decrease_percent > 0) {
            $time *= (100 - $decrease_percent) / 100;
        }
        $time *= $alliance_effect;
        //it should be round instead of floor
        if (getGameSpeed() <= 10) {
            $time = round($time);
        }
        // At least one second, stored in this queue's unit (1 s, 1 ms or 1 ns).
        // Never zero: a training_time of 0 marks a row as complete.
        return max(floor($time), self::minimumQueueDuration());
    }

    /**
     * Healing takes half the training time of the unit at the same building level
     * and follows the world speed like training. Artefacts, alliance bonuses, hero
     * items and the horse drinking trough do not apply (Knowledge Base article 77).
     *
     * @param int $unitId
     * @param int $buildingLevel
     */
    public static function uHealingTime($unitId, $buildingLevel): int
    {
        // Half the training time, and at least one second in the queue's unit.
        $half = (int)round(self::uTrainingTime($unitId, $buildingLevel) * Wounded::HEAL_TIME_FACTOR);

        return max(self::minimumQueueDuration(), $half);
    }

