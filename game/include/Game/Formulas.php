    /**
     * Cumulative resources the alliance must have donated to reach a level.
     * Knowledge Base article 88 (2026-11-01): 1.2M / 5.6M / 17.1M / 51.2M / 153.6M.
     *
     * @param int $level
     * @return float|int
     */
    public static function getAllianceBonusContributesNeededForLevel($level)
    {
        $rate = 1;
        if (getGameSpeed() > 20) {
            // An int, so the thresholds stay integers at every speed (ceil() alone returns a float).
            $rate = (int)ceil(getGameSpeed() / 1000);
        }
        $result = [
            0 => 0,
            1 => 1200000,
            2 => 5600000,
            3 => 17100000,
            4 => 51200000,
            5 => 153600000,
        ];

        return $rate * ($result[$level] ?? 0);
    }

