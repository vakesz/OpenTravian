            }
        }
        return $cost;
    }

    /**
     * @param mixed $unitId
     * @return mixed
     */
    public static function uResearchTime($unitId)
    {
        // Unit training already applies the world-speed profile.  Research has
        // a fixed Academy overhead as well, so compute its base duration and
        // scale the entire operation exactly once.  The previous calculation
        // only scaled the training component, leaving every research with an
        // unscaled 30-minute (or two-hour Senator) floor.
        $speed = max(1, getGameSpeed() * getGame('extra_training_time_multiplier'));
        $u = unitIdToNr($unitId) - 1;
        // Use the unit's unscaled base duration.  Reversing uTrainingTime()
        // here would be lossy at extreme speed because it deliberately floors
        // training to one second.
        $trainingTime = $unitId == 99
            ? 600
            : self::$data['units'][unitIdToTribe($unitId) - 1][$u]['time'];
        if ($u < 8) { //normal troops
            $duration = (1800 + 3 * $trainingTime) / $speed;
        } else {
            // Chiefs: (training time + 7200) / 4, as kirilloid lists them.
            $duration = (7200 + $trainingTime) / 4 / $speed;
        }

        // Research end times live in the INTEGER Unix-seconds column used by
        // the Academy, Smithy, automation, and admin flows.  Keep that one
        // shared contract even when troop training uses sub-second precision.
        return max(1, getGameSpeed() <= 20 ? round5($duration) : (int)ceil($duration));
    }

    /**
     * @param mixed $unitId
     * @param (float|int) $lvl
     * @return mixed
     */
    public static function uUpgradeCost($unitId, $lvl)
    {
        $c = pow($lvl, 0.8);
        $cost = self::uTrainingCost($unitId);
        $coeffs = self::uResearchCostCoeffs($unitId);
        for ($r = 0; $r < 4; $r++) {
            $k = ($cost[$r] * 7 + $coeffs['b'][$r]) / self::uUpkeep($unitId);

            $cost[$r] = round5($k * $c);
        }

        return $cost;
    }

    /**
     * @param mixed $u
     * @param (float|int) $lvl
     * @param mixed $b_level
     */
    public static function uUpgradeTime($u, $lvl, $b_level): int
    {
        $researchTime = self::uResearchTime($u);
        $c = pow($lvl, 0.8);
        $tc = pow(0.964, $b_level - 1);
        // At extreme game speeds the base research duration intentionally
        // bottoms out at one second.  The Academy/Smithy modifier is applied
        // afterwards, so rounding without a second guard could turn a valid
        // upgrade into a zero-second job.  Queue and automation timestamps
        // are integer Unix seconds and must always advance.
        return max(1, (int)round($researchTime * $c * $tc));
    }

