    /**
     * @param mixed $gid
     * @param mixed $lvl
     * @param mixed $mb
     * @param mixed $n
     * @return mixed
     */
    public static function buildingUpgradeTime($gid, $lvl, $mb, $n = FALSE)
    {
        $rate = getGameSpeed();
        $t = array_values(self::$data['buildings'][$gid - 1]['time']);

        if (sizeof($t) < 3) {
            $t[1] = 1.16;
            if (sizeof($t) === 1) {
                $t[1] = 1;
            }
            $t[2] = 1875 * $t[1];
        }

        // The official calculator stores World Wonder levels as the exact
        // closed form of `next = current * 1.014 + 600`. Preserve that
        // published x1-x10 calculation without changing the documented local
        // high-speed path above x10.
        if ($gid == 40 && $rate <= 10) {
            $t = [426000 / 7, 1.014, 300000 / 7];
        }

        $time = (($t[0] * pow($t[1], $lvl - 1) - $t[2]) * ($mb != 0 ? pow(0.964,
                $mb - 1) : 5) / $rate / ($n ? 2 : 1));

        // World Wonders keep their own half-time rule after world-speed and
        // Main Building scaling. This mirrors the official building calculator,
        // including the two ten-second rounding steps at every published speed.
        if ($gid == 40) {
            return max(1, round10(round10($time) / 2));
        }

        // The official calculator displays ordinary construction rounded to
        // ten seconds through its highest published speed (x10). Keep the
        // local sub-ten-second high-speed policy strictly above that range.
        return max(1, $rate <= 10 ? round10($time) : round($time));
    }

    /**
     * @param mixed $gid
     * @param mixed $lvl
     * @return mixed
     */
    public static function buildingUpgradeCosts($gid, $lvl)
    {
        if (!$gid) {
            return [0, 0, 0, 0];
        }
        if ($gid == 99) {
            $gid = 40;
        }//w :>
        $cost = self::$data['buildings'][$gid - 1]['cost'];
        $k = self::$data['buildings'][$gid - 1]['k'];
        for ($r = 0; $r < 4; ++$r) {
            $cost[$r] = round($cost[$r] * pow($k, $lvl - 1) / 5) * 5;
            if ($gid == 40) {
                if ((($lvl == 100) && ($r < 3)) || ($cost[$r] > 1e6)) {
                    $cost[$r] = 1e6;
                }
            }
        }
        if ($gid <= 4 && $lvl > 20 && getGameSpeed() > 10) {
            $rate = 10;
            foreach ($cost as &$r) {
                $r *= $rate;
            }
        }
        return $cost;
    }

    /**
     * @param mixed $item_id
     * @param mixed $lvl
     * @param (array<mixed>|float|int)|(float|int)|int $to_lvl
     * @param bool $noCP
     * @return list<(float|int)>
     */
    public static function buildingCpPop($item_id, $lvl, $to_lvl, $noCP = FALSE)
    {
        $pop = 0;
        $tmp1 = min($lvl, $to_lvl);
        $tmp2 = max($lvl, $to_lvl);
        $diff = $tmp2 - $tmp1;
        for ($i = 1; $i <= $diff; ++$i) {
            $pop += self::buildingCropConsumption($item_id, $tmp1 + $i);
        }
        $cp = abs(-self::buildingCP($item_id, $lvl) + self::buildingCP($item_id, $to_lvl));
        return [$pop, $noCP ? 0 : $cp];
    }

    /**
     * @param mixed $gid
     * @param mixed $lvl
     * @param mixed $n
     * @return mixed
     */
    public static function buildingCropConsumption($gid, $lvl, $n = false)
    {
        if ($lvl <= 0) {
            return 0;
        }
        if (!isset(self::$data['buildings'][$gid - 1]['cu'])) {
            return 0;
        }
        $cu = self::$data['buildings'][$gid - 1]['cu'];

        //if ($n && C("Game.version") < 4) $cu /= 2;
        return ($lvl <> 1) ? round((5 * $cu + ($lvl - 1)) / 10) : $cu;
    }

    /**
     * @param mixed $gid
     * @param mixed $lvl
     * @return float|int
     */
    public static function buildingCP($gid, $lvl)
    {
        if ($lvl <= 0) {
            return 0;
        }
        if (!isset(self::$data['buildings'][$gid - 1])) {
            return 0;
        }

        return round(self::$data['buildings'][$gid - 1]['cp'] * pow(1.2, $lvl));
    }

    /**
     * @param mixed $gid
     * @param mixed $capital
     * @param bool $real
     * @return float|int
     */
    public static function buildingMaxLvl($gid, $capital, $real = true)
    {
        if ($gid == 40) return 100;
        if ($gid <= 4) {
            if (!$capital) {
                return 10;
            }
            return !$real ? 20 : (getCustom('allowResourcesToGoToMaximumPossible') ? 1e9 : 21);
        }
        return (int)self::$data['buildings'][$gid - 1]['maxLvl'];
    }

    /**
     * @param mixed $cp
     */
    public static function countCPVillages($cp): int
    {
        $multiplier = ceil(getGame('movement_speed_increase') / 50);
        $speed = min(getGameSpeed(), 10);
        $n = max(1, (int)floor(pow(max(0, $cp) / 1600 * $speed / $multiplier, 1 / 2.3) + 1));
        while ($n > 1 && $cp < self::newVillageCP($n)) {
            $n--;
        }
        while ($cp >= self::newVillageCP($n + 1)) {
            $n++;
        }
        return $n;
    }

    /**
     * @param mixed $n
     */
    public static function newVillageCP($n): float
    {
        $multiplier = ceil(getGame('movement_speed_increase') / 50);
        $speed = min(getGameSpeed(), 10);
        return $multiplier * round(1600 * pow($n - 1, 2.3) / $speed, $speed >= 2 ? -2 : -3);
    }

