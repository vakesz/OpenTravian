    /**
     * Returns the persisted-experience scale for a world-speed profile.
     *
     * Keeping this independent from the active configuration lets a speed
     * profile migration rescale existing hero experience without briefly
     * loading the old world configuration into the running application.
     *
     * @param mixed $speed
     */
    public static function heroExpLevelMultiplierForSpeed($speed): int
    {
        $speed = max(1, (int)$speed);
        $x = 1;
        //fix of levels
        if ($speed <= 10) {
            $x = 1;
        } else if ($speed <= 1000) {
            $x = 20;
        } else if ($speed <= 2000) {
            $x = 40;
        } else if ($speed <= 3000) {
            $x = 60;
        } else if ($speed <= 5000) {
            $x = 100;
        } else if ($speed <= 10000) {
            $x = 300;
        } else if ($speed <= 20000) {
            $x = 600;
        } else {
            $x = (int)ceil($speed * 3 / 100);
        }
        return $x;
    }

    /**
     * @param mixed $level
     * @return (float|int)
     */
    public static function heroExperience($level)
    {
        $x = self::getHeroExpLevelMultiplier();
        return $x * 25 * $level * ($level + 1);
    }

    /**
     * @param mixed $level
     */
    public static function heroRegenerationTime($level): float
    {
        $rate = Config::getProperty("game", "useNanoseconds") ? 1e9 : (Config::getProperty("game",
            "useMilSeconds") ? 1e3 : 1);
        $speed = (int)getGameSpeed();
        if ($level >= 99 && WorldSpeedProfile::isOfficialLegendsSpeed($speed)) {
            $hours = 24 * (99 / (99 + ($level - 99) * 5));
        } else {
            $hours = min($level + 1, 24) / WorldSpeedProfile::heroRevivalDivisor($speed);
        }

        return round($hours * 3600 * $rate);
    }

    /**
     * @param mixed $lvl
     * @param mixed $tribe_id
     * @return array<int, mixed>
     */
    public static function heroRegenerateCost($lvl, $tribe_id)
    {
        $tribe_costs = [
            1 => [130, 115, 180, 75],
            2 => [180, 130, 115, 75],
            3 => [115, 180, 130, 75],
            5 => [130, 115, 180, 75],
            6 => [115, 180, 130, 75],
            7 => [125, 125, 125, 125],
            // Spartans and Vikings: kirilloid hero4 tribe_costs.
            8 => [150, 150, 150, 75],
            9 => [150, 150, 150, 75],
            //natars are same as romans.
        ];
        $cost = [];
        $lvl = min($lvl, 100);
        for ($r = 0; $r < 4; $r++) {
            $cost[$r] = self::trickyRounding($tribe_costs[$tribe_id][$r] * (1 + $lvl / 24) * (1 + $lvl), $lvl);
        }
        return $cost;
    }

    /**
     * @param (float|int) $value
     * @param mixed $lvl
     */
    private static function trickyRounding($value, $lvl): float
    {
        if ($lvl < 5) {
            $round_size = 10;
        } else if ($lvl < 10) {
            $round_size = 50;
        } else {
            $round_size = 100;
        }

        return round($value / $round_size) * $round_size;
    }

