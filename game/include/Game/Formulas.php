    /**
     * @param mixed $x
     * @param mixed $y
     * @param int $max_distance
     * @return array<string, float>
     */
    public static function getNearbyXY($x, $y, $max_distance)
    {
        $angle = atan2($y, $x);
        $r = hypot($x, $y);
        $half = $max_distance / 2;
        $pointRadius = mt_rand((int)($r - $half), (int)($r + $half));
        $point = [
            'x' => ceil(cos($angle) * $pointRadius),
            'y' => ceil(sin($angle) * $pointRadius),
        ];
        return $point;
    }

    /**
     * @param mixed $x
     * @param mixed $y
     */
    public static function getXYAngle($x, $y): float
    {
        $angle = rad2deg(atan2($y, $x));
        if ($angle < 0) {
            $angle += 360;
        }
        return $angle;
    }

