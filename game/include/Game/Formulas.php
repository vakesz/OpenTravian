            return $stdCost;
        } else if ($u == 8) {
            return $adminCost;
        }

        return $nullCost;
    }

    /**
     * @param mixed $u
     * @param mixed $big
     * @return mixed
     */
    public static function uTrainingCost($u, $big = FALSE)
    {
        if ($u == 99) {
            return [35, 30, 10, 20];
        } //trap
        $race = unitIdToTribe($u);
        if ($race == 5) $race = 1; // Natars to roman
        $race = $race - 1;
        $u = unitIdToNr($u) - 1;
        $cost = self::$data['units'][$race][$u]['cost'];
